namespace InkRecognition;

public sealed partial class LegacyNativeLaterDictionaryWordCompletion
{
    private readonly CaseSpanBinding? caseSpan;

    /// <summary>Fresh one-source292 later-word consumer. The span is the live
    /// last D0 map lease; its span need not equal the current word's anchor span.
    /// Actual history/context rows and frontend E8 remain owned supplied inputs.
    /// Previous-node rows must contain exactly SourceEnd23F0 entries.</summary>
    public static LegacyNativeLaterDictionaryWordCompletion ForFreshCaseSpan(
        LegacyFreshCaseMainSourcePolicy policy, LegacyOwnedMainWordSpan span,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(policy);
        ArgumentNullException.ThrowIfNull(span);
        cancellationToken.ThrowIfCancellationRequested();
        var owner = policy.Controller.Owner;
        if (!ReferenceEquals(span.Owner, owner) || !ReferenceEquals(owner.CaseDictionaryOwner, policy.DictionaryOwner) ||
            !ReferenceEquals(owner.CommonModel, policy.Model) || !ReferenceEquals(owner.SourceGraph, policy.Graph))
            throw new ArgumentException("Actual fresh case source/controller/span/model/ordinary graph owner required.");
        owner.ValidateSpan(span, cancellationToken);
        var configuration = policy.Controller.Configuration;
        if (configuration.Mode22f6 != 0 || configuration.Trace2368 != 0 ||
            !float.IsFinite(policy.Controller.SecondaryScaleEc) || policy.Controller.SecondaryScaleEc > 0 ||
            policy.HasAssociatedSource || policy.ConfiguredSourceCount != 1)
            throw new NotSupportedException("Fresh ordinary mode0/nonpositive ec/nontracing one-source case policy required.");
        //222.V280/155710 -> this ordinary21B.V1C8/05A400 is false.
        //The absent associated source alone would not prove this getter.
        return new(policy, span);
    }

    private LegacyNativeLaterDictionaryWordCompletion(LegacyFreshCaseMainSourcePolicy policy, LegacyOwnedMainWordSpan span)
    {
        alphabet = policy.Model.AcousticAlphabet;
        categories = policy.Model.CreateCursiveCategoryMapper(1);
        categoryPolicy = new(categories);
        language = policy.DictionaryOwner.LanguageRecords;
        sourceId = 1;
        sourceHeader = policy.DictionaryOwner.Descriptor.Flags;
        if (!language.IsForModel(policy.Model) || (sourceHeader & 0x1e00) != 0xc00 || (sourceHeader & 0x1c) <= 7)
            throw new ArgumentException("Actual order2/C00 source and its language profiles required.");
        if (!alphabet.TryGetLabel("\ufffd", out replacement) || !alphabet.TryGetLabel("-", out dash))
            throw new NotSupportedException("Actual replacement and dash source labels required.");
        caseSpan = new(policy, span);
    }

    /// <summary>Consume the actual source query32, without replacing its tag,
    /// context, cost, symbol or kind with a current-terminal injection. Ordinary
    /// nonvirtual punctuation is supported; protocol/force branches still refuse.
    /// This does not prove that the supplied page was generated by the scheduler.</summary>
    public LegacyNativeLaterDictionaryWordCompletionResult ProcessActualQuery(ReadOnlySpan<byte> query32,
        LegacyNativeLanguageContextRecombinationResult contextResult, int candidateIndex,
        int endingNode, ushort currentRowOrdinal, int availableSourceNodes,
        Func<int, IReadOnlyList<LegacyNativeStoredWordRecord>> owningNodeRowsLookup,
        Func<byte, uint> preparedSourceHeader, Func<int, int, int> descriptorLineE8,
        LegacySymbolContextFactory contexts, LegacyNativeWordHeapRouter router,
        bool knowledgeF5, int subwordSourceIndex22ec, bool extendedMarkers22f8,
        ReadOnlySpan<byte> temporaryLexicalResidue40, bool suppressPrevious2609,
        CancellationToken cancellationToken = default)
    {
        if (Interlocked.CompareExchange(ref active, 1, 0) != 0)
            throw new InvalidOperationException("Native later-word completion calls must be serialized.");
        try
        {
            if (!valid) throw new InvalidOperationException("Failed later-word completion requires a fresh producer.");
            cancellationToken.ThrowIfCancellationRequested();
            if (query32.Length != 32) throw new ArgumentException("Actual complete query32 required.");
            byte[] query = query32.ToArray();
            return ProcessCore(contextResult, candidateIndex, endingNode, currentRowOrdinal, availableSourceNodes,
                owningNodeRowsLookup, preparedSourceHeader, descriptorLineE8, contexts, router,
                knowledgeF5, subwordSourceIndex22ec, extendedMarkers22f8, new byte[32], temporaryLexicalResidue40,
                suppressPrevious2609, cancellationToken, query);
        }
        catch { valid = false; throw; }
        finally { Volatile.Write(ref active, 0); }
    }

    private sealed class CaseSpanBinding(LegacyFreshCaseMainSourcePolicy policy, LegacyOwnedMainWordSpan span)
    {
        private LegacyOwnedMainWordSpanPreparation Owner => policy.Controller.Owner;
        private readonly uint[] headers = policy.Controller.Owner.CopySourceHeaders();
        public void Validate(int endingNode, LegacySymbolContextFactory contexts, bool knowledgeF5,
            int subwordSourceIndex22ec, bool extendedMarkers22f8, bool suppressPrevious2609, CancellationToken token)
        {
            Owner.ValidateSpan(span, token);
            if (endingNode != span.EndingNode || !ReferenceEquals(contexts, Owner.Contexts) ||
                knowledgeF5 != policy.Controller.KnowledgeF5 || subwordSourceIndex22ec != Owner.CommonSourceSummary.LastKind800Source ||
                extendedMarkers22f8 || suppressPrevious2609 != (policy.Controller.Configuration.SuppressPreviousContext2609 != 0))
                throw new ArgumentException("Actual fresh node/context/source/history flags required.");
        }
        //203987..2039B0 and203C59 enumerate [230A,23F0). The supplied
        //previous-node collection must end at SourceEnd23F0, not capacity or
        //RetainedEnd23F8; shared core checks the upper bound against its count.
        public void ValidateSecondaryOrdinal(ushort ordinal)
        {
            if (ordinal < policy.Controller.Configuration.PrimaryArcLimit230a)
                throw new ArgumentException("Language context+C must select an actual secondary row, not a primary anchor reference.");
        }
        public void ValidateExtent(int count)
        {
            if (count != policy.Graph.NodeCount) throw new ArgumentException("Actual source graph node extent required.");
        }
        public void ValidateHeader(byte id, uint header)
        {
            if (id >= headers.Length || header != headers[id]) throw new ArgumentException("Actual selected source header required.");
        }
        public ReadOnlyMemory<byte> ReadTerminal(ulong tag, ushort symbol, CancellationToken token)
            => Owner.ReadWordTerminal(span, tag, symbol, 0, token);
        public ulong ResolveRestart(ulong tag, CancellationToken token) => Owner.ResolveWordRestart(span, tag, token);
    }
}
