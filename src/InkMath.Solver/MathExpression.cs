using System.Globalization;

namespace InkMath.Solver;

internal abstract record Expression
{
    internal abstract string Cas { get; }
    internal abstract IEnumerable<string> Variables { get; }
}
internal sealed record Number(string Value) : Expression
{
    internal override string Cas => Value; internal override IEnumerable<string> Variables => [];
}
internal sealed record Variable(string Name) : Expression
{
    internal override string Cas => Name; internal override IEnumerable<string> Variables => Name is "pi" or "e" or "i" or "infinity" ? [] : [Name];
}
internal sealed record Binary(string Operator, Expression Left, Expression Right) : Expression
{
    internal override string Cas => "(" + Left.Cas + Operator + Right.Cas + ")";
    internal override IEnumerable<string> Variables => Left.Variables.Concat(Right.Variables);
}
internal sealed record Call(string Name, params Expression[] Arguments) : Expression
{
    internal override string Cas => Name + "(" + string.Join(',', Arguments.Select(a => a.Cas)) + ")";
    internal override IEnumerable<string> Variables => (Name is "sum" or "product" or "limit" || Name == "integrate" && Arguments.Length == 4) && Arguments.Length >= 2 && Arguments[1] is Variable bound
        ? Arguments[0].Variables.Where(v => v != bound.Name).Concat(Arguments.Skip(2).SelectMany(a => a.Variables))
        : Arguments.SelectMany(a => a.Variables);
}
internal sealed record Matrix(Expression[][] Rows) : Expression
{
    internal override string Cas => "[" + string.Join(',', Rows.Select(r => "[" + string.Join(',', r.Select(e => e.Cas)) + "]")) + "]";
    internal override IEnumerable<string> Variables => Rows.SelectMany(r => r).SelectMany(e => e.Variables);
}

// A math grammar, not a general-purpose CAS/Python parser. Every executable
// function is generated by this parser; raw identifiers/commands never pass through.
internal sealed class MathExpressionParser
{
    private readonly string _source;
    private int _position, _depth, _nodes;
    private bool _differentialStop;
    internal MathExpressionParser(string source)
    {
        if (source.Length is 0 or > 4096 || source.Any(c => char.IsControl(c) && !char.IsWhiteSpace(c))) throw new FormatException("Invalid mathematics input.");
        _source = source.Replace("\\,", " ", StringComparison.Ordinal).Replace("\\;", " ", StringComparison.Ordinal).Replace("\\!", "", StringComparison.Ordinal)
            .Replace("−", "-", StringComparison.Ordinal).Replace("×", "*", StringComparison.Ordinal).Replace("÷", "/", StringComparison.Ordinal);
    }
    internal Expression Parse()
    {
        var value = Relation(); White(); if (_position != _source.Length) throw new FormatException("Incomplete or unsupported mathematics."); return value;
    }
    private void White() { while (_position < _source.Length && char.IsWhiteSpace(_source[_position])) _position++; }
    private bool At(string text) { White(); return _source.AsSpan(_position).StartsWith(text, StringComparison.Ordinal); }
    private bool Take(string text) { if (!At(text)) return false; _position += text.Length; return true; }
    private void Require(string text) { if (!Take(text)) throw new FormatException("Expected " + text); }
    private Expression Relation()
    {
        var left = Add(); if (Take("=")) return Count(new Binary("=", left, Add())); return left;
    }
    private T Count<T>(T value) where T : Expression { if (++_nodes > 512) throw new FormatException("Mathematics complexity limit."); return value; }
    private Expression Add()
    {
        var value = Multiply();
        while (true)
        {
            if (Take("+")) value = Count(new Binary("+", value, Multiply()));
            else if (Take("-")) value = Count(new Binary("-", value, Multiply()));
            else return value;
        }
    }
    private bool Differential()
    {
        White(); return _source.AsSpan(_position).StartsWith("\\mathrm{d}", StringComparison.Ordinal) ||
            _source.AsSpan(_position).StartsWith("\\mathrm {d}", StringComparison.Ordinal) ||
            _source.AsSpan(_position).StartsWith("\\text{d}", StringComparison.Ordinal) ||
            _position + 1 < _source.Length && _source[_position] == 'd' && (char.IsLetter(_source[_position + 1]) || char.IsWhiteSpace(_source[_position + 1]));
    }
    private bool StartsAtom()
    {
        White(); if (_position == _source.Length || _differentialStop && Differential()) return false;
        if (At("\\end") || At("\\\\") || At("\\right")) return false;
        return char.IsLetterOrDigit(_source[_position]) || _source[_position] is '(' or '{' or '[' or '\\' or 'π' or '∞' or '∫' or '∑';
    }
    private Expression Multiply()
    {
        var value = Unary();
        while (true)
        {
            if (_differentialStop && Differential()) return value;
            if (Take("*") || Take("\\cdot") || Take("\\times")) value = Count(new Binary("*", value, Unary()));
            else if (Take("/") || Take("\\div")) value = Count(new Binary("/", value, Unary()));
            else if (StartsAtom()) value = Count(new Binary("*", value, Unary()));
            else return value;
        }
    }
    private Expression Unary()
    {
        if (++_depth > 32) throw new FormatException("Mathematics nesting limit.");
        try
        {
        if (Take("+")) return Unary();
        if (Take("-")) return Count(new Binary("*", new Number("-1"), Unary()));
        var value = Atom();
        if (Take("_"))
        {
            var index = ScriptArgument();
            if (value is not Variable variable || index is not Number number || number.Value.Any(c => !char.IsAsciiDigit(c)) || number.Value.Length > 3) throw new FormatException("Unsupported variable index.");
            value = Count(new Variable(variable.Name + "_" + number.Value));
        }
        if (Take("^")) value = Count(new Binary("^", value, Take("{") ? Group("}") : Unary()));
        while (Take("!")) value = Count(new Call("factorial", value));
        return value;
        }
        finally { _depth--; }
    }
    private Expression Argument() => Take("{") ? Group("}") : Take("(") ? Group(")") : Unary();
    private Expression ScriptArgument() => Take("{") ? Group("}") : Atom();
    private Expression Group(string close)
    {
        if (++_depth > 32) throw new FormatException("Mathematics nesting limit.");
        var value = Relation(); Require(close); _depth--; return value;
    }
    private string Command()
    {
        Require("\\"); var start = _position;
        while (_position < _source.Length && char.IsAsciiLetter(_source[_position])) _position++;
        if (start == _position) throw new FormatException("Unsupported mathematics command.");
        return _source[start.._position];
    }
    private Expression Atom()
    {
        White(); if (++_depth > 32) throw new FormatException("Mathematics nesting limit.");
        try
        {
            if (Take("{") || Take("(")) return Group(_source[_position - 1] == '{' ? "}" : ")");
            if (_position == _source.Length) throw new FormatException("Missing mathematics operand.");
            if (char.IsAsciiDigit(_source[_position]) || _source[_position] == '.')
            {
                int start = _position; while (_position < _source.Length && (char.IsAsciiDigit(_source[_position]) || _source[_position] == '.')) _position++;
                var text = _source[start.._position];
                if (text.Length > 100 || !double.TryParse(text, NumberStyles.AllowDecimalPoint, CultureInfo.InvariantCulture, out var number) || !double.IsFinite(number)) throw new FormatException("Invalid number.");
                return Count(new Number(text));
            }
            if (Take("π")) return Count(new Variable("pi"));
            if (Take("∞")) return Count(new Variable("infinity"));
            if (Take("∫")) return Integral();
            if (Take("∑")) return Aggregate("sum");
            if (At("\\"))
            {
                var command = Command();
                if (Greek.TryGetValue(command, out var greek)) return Count(new Variable(greek));
                switch (command)
                {
                    case "left": return Fence();
                    case "frac": case "dfrac": case "tfrac":
                        if (TryDerivative(out var derivative)) return derivative;
                        return Count(new Binary("/", Argument(), Argument()));
                    case "sqrt":
                        if (Take("[")) { var root = Group("]"); return Count(new Binary("^", Argument(), new Binary("/", new Number("1"), root))); }
                        return Count(new Call("sqrt", Argument()));
                    case "int": return Integral();
                    case "sum": case "prod": return Aggregate(command);
                    case "lim": return Limit();
                    case "begin": return ReadMatrix();
                    case "operatorname":
                        Require("{"); int nameStart = _position;
                        while (_position < _source.Length && char.IsAsciiLetter(_source[_position])) _position++;
                        command = _source[nameStart.._position]; Require("}"); break;
                    case "mathrm": case "text":
                        Require("{"); int start = _position;
                        while (_position < _source.Length && char.IsAsciiLetter(_source[_position])) _position++;
                        var word = _source[start.._position]; Require("}");
                        if (word.Length == 1) return Count(new Variable(word));
                        command = word; break;
                }
                if (!Functions.TryGetValue(command, out var function)) throw new FormatException("Unsupported mathematical function: " + command);
                Expression? power = null;
                if (Take("^")) power = Argument();
                var value = Count(new Call(function, Argument()));
                return power is null ? value : Count(new Binary("^", value, power));
            }
            foreach (var function in OrderedFunctions)
                if (At(function.Key)) { _position += function.Key.Length; return Count(new Call(function.Value, Argument())); }
            if (char.IsAsciiLetter(_source[_position])) return Count(new Variable(_source[_position++].ToString()));
            throw new FormatException("Unsupported mathematics operand.");
        }
        finally { _depth--; }
    }
    private (Expression? Lower, Expression? Upper) Bounds()
    {
        Expression? lower = null, upper = null;
        while (true)
        {
            if (Take("_")) { if (lower is not null) throw new FormatException("Duplicate lower bound."); lower = ScriptArgument(); }
            else if (Take("^")) { if (upper is not null) throw new FormatException("Duplicate upper bound."); upper = ScriptArgument(); }
            else break;
        }
        return (lower, upper);
    }
    private string Delimiter()
    {
        White();
        foreach (var delimiter in new[] { "\\{", "\\}", "\\Vert" }) if (Take(delimiter)) return delimiter;
        if (_position < _source.Length && _source[_position] is '(' or ')' or '[' or ']' or '|' or '.') return _source[_position++].ToString();
        throw new FormatException("Unsupported math fence.");
    }
    private Expression Fence()
    {
        var left = Delimiter();
        var right = left switch { "(" => ")", "[" => "]", "|" => "|", "\\{" => "\\}", _ => throw new FormatException("Unsupported math fence.") };
        var body = Relation(); Require("\\right"); var actualRight = Delimiter();
        if (actualRight != right && !(actualRight == "." && left == "\\{" && body is Matrix)) throw new FormatException("Unbalanced math fence.");
        if (left == "\\{")
        {
            if (body is not Matrix matrix || !matrix.Rows.SelectMany(r => r).All(e => e is Binary { Operator: "=" })) throw new FormatException("Unsupported set/piecewise notation.");
            return body;
        }
        return left == "|" ? Count(new Call(body is Matrix ? "det" : "abs", body)) : body;
    }
    private Expression Integral()
    {
        var (lower, upper) = Bounds(); if ((lower is null) != (upper is null)) throw new FormatException("Both integral bounds are required.");
        var previous = _differentialStop; _differentialStop = true;
        Expression body;
        try { body = Add(); } finally { _differentialStop = previous; }
        if (!(Take("\\mathrm{d}") || Take("\\mathrm {d}") || Take("\\text{d}") || Take("d"))) throw new FormatException("Integral needs an explicit differential.");
        var variable = Atom(); if (variable is not Variable) throw new FormatException("Invalid integration variable.");
        return Count(lower is null ? new Call("integrate", body, variable) : new Call("integrate", body, variable, lower, upper!));
    }
    private Expression Aggregate(string function)
    {
        var (lower, upper) = Bounds();
        if (lower is not Binary { Operator: "=", Left: Variable variable } bound || upper is null) throw new FormatException("Sum/product needs variable and both bounds.");
        return Count(new Call(function == "prod" ? "product" : function, Add(), variable, bound.Right, upper));
    }
    private Expression Limit()
    {
        Require("_"); Require("{"); var variable = Atom();
        if (variable is not Variable) throw new FormatException("Limit requires a variable.");
        Require("\\to"); var target = Add(); Require("}");
        return Count(new Call("limit", Add(), variable, target));
    }
    private bool TryDerivative(out Expression derivative)
    {
        derivative = null!; var saved = _position;
        if (!Take("{")) { _position = saved; return false; }
        bool partial = Take("\\partial"); if (!partial && !Take("d")) { _position = saved; return false; }
        Expression order = new Number("1"); if (Take("^")) order = Argument();
        if (!Take("}") || !Take("{")) { _position = saved; return false; }
        if (!(partial ? Take("\\partial") : Take("d"))) { _position = saved; return false; }
        var variable = Atom(); if (variable is not Variable) { _position = saved; return false; }
        Expression denominatorOrder = new Number("1"); if (Take("^")) denominatorOrder = Argument();
        if (!Take("}") || order != denominatorOrder || order is not Number { Value: var n } || !int.TryParse(n, out var integer) || integer is < 1 or > 16) { _position = saved; return false; }
        derivative = Count(new Call("diff", Add(), variable, order)); return true;
    }
    private Expression ReadMatrix()
    {
        Require("{"); int start = _position;
        while (_position < _source.Length && char.IsAsciiLetter(_source[_position])) _position++;
        var environment = _source[start.._position]; Require("}");
        if (environment is not ("matrix" or "pmatrix" or "bmatrix" or "vmatrix" or "cases" or "array")) throw new FormatException("Unsupported matrix environment.");
        if (environment == "array")
        {
            Require("{"); int columns = 0;
            while (_position < _source.Length && _source[_position] is 'l' or 'c' or 'r' or '|') { _position++; if (++columns > 24) throw new FormatException("Matrix column limit."); }
            Require("}");
        }
        var rows = new List<Expression[]>(); var row = new List<Expression>();
        while (true)
        {
            row.Add(Relation()); if (row.Count > 12 || rows.Count >= 12) throw new FormatException("Matrix dimension limit.");
            if (Take("&")) continue;
            rows.Add(row.ToArray()); row.Clear();
            if (Take("\\\\")) continue;
            Require("\\end{" + environment + "}"); break;
        }
        if (rows.Any(r => r.Length != rows[0].Length)) throw new FormatException("Ragged matrix.");
        var matrix = Count(new Matrix(rows.ToArray())); return environment == "vmatrix" ? Count(new Call("det", matrix)) : matrix;
    }
    private static readonly Dictionary<string, string> Functions = new(StringComparer.Ordinal)
    {
        ["sin"]="sin", ["cos"]="cos", ["tan"]="tan", ["cot"]="cot", ["sec"]="sec", ["csc"]="csc",
        ["arcsin"]="asin", ["arccos"]="acos", ["arctan"]="atan", ["sinh"]="sinh", ["cosh"]="cosh", ["tanh"]="tanh",
        ["ln"]="ln", ["log"]="log", ["exp"]="exp", ["abs"]="abs", ["det"]="det", ["rank"]="rank", ["trace"]="trace", ["inv"]="inv",
        ["factor"]="factor", ["expand"]="expand", ["eigenvalues"]="eigenvals"
    };
    private static readonly KeyValuePair<string,string>[] OrderedFunctions = Functions.OrderByDescending(p => p.Key.Length).ToArray();
    private static readonly Dictionary<string, string> Greek = new(StringComparer.Ordinal)
    {
        ["pi"]="pi", ["infty"]="infinity", ["alpha"]="alpha", ["beta"]="beta", ["gamma"]="gamma", ["delta"]="delta",
        ["epsilon"]="epsilon", ["theta"]="theta", ["lambda"]="lambda", ["mu"]="mu", ["sigma"]="sigma", ["phi"]="phi", ["omega"]="omega"
    };
}
